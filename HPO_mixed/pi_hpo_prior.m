function [pi_hg, pi_bnd, pi_merged, C] = pi_hpo_prior()
C = struct( ...
  'good_lo',   0.54, ...
  'good_hi',   0.76, ...
  'ew',        0.08, ...
  'floor',     0.01, ...
  'ov_lo',     [0.70 0.25], ...
  'ov_hi',     [1.00 1.00], ...
  'shell_tg',  0.08);
pi_hg = @(X) band1(X(:,1), C.good_lo, C.good_hi, C.ew, C.floor);
pi_bnd = @(X) box_shell(X, C);
pi_merged = @(X) max(pi_hg(X), pi_bnd(X));
end
function v = band1(u, lo, hi, ew, fl)
dout = max(max(lo - u, 0), u - hi);
v = min(max(exp(-0.5 * (dout / ew).^2), fl), 1);
end
function v = box_shell(X, C)
d = [min(abs(X(:,1) - C.ov_lo(1)), abs(X(:,1) - C.ov_hi(1))), ...
     min(abs(X(:,2) - C.ov_lo(2)), abs(X(:,2) - C.ov_hi(2)))];
dface = min(d, [], 2);
v = min(max(exp(-0.5 * (dface / C.shell_tg).^2), C.floor), 1);
end
