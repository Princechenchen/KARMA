function [pi_hg, pi_hg2, pri] = pi_wingweight_prior8(X)
LO_MAT = local_mat_lo();
HI_MAT = local_mat_hi();
if nargin >= 1 && ~isempty(X)
    pi_hg = local_pi(X, LO_MAT, HI_MAT);
    pi_hg2 = pi_hg; pri = [];
    return;
end
pi_hg  = @(Xq) local_pi(Xq, LO_MAT, HI_MAT);
pi_hg2 = pi_hg;
pri = struct('n_win', 31, 'rhomax', 1364.0, 'label', '第20步ROI密度场(31窗, rho/rhomax)');
pri.lo = LO_MAT; pri.hi = HI_MAT;
end
function y = local_pi(X, LO_MAT, HI_MAT)
n = size(X, 1);
d = zeros(n, 1);
for w = 1:size(LO_MAT, 1)
    inm = true(n, 1);
    for dd = 1:10
        inm = inm & (X(:, dd) >= LO_MAT(w, dd)) & (X(:, dd) <= HI_MAT(w, dd));
    end
    wv = prod(HI_MAT(w, :) - LO_MAT(w, :));
    d = d + double(inm) / max(wv, 1e-9);
end
y = max(0.01, d / 1364.0);
end
