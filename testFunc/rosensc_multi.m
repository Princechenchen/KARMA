function y = rosensc_multi(xx)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
% 多输出版重新缩放罗森布罗克函数 (适用于多输出高斯过程模型建模)
% 输出说明：
%   y1: 连续型输出1 (核心罗森布罗克函数值，轻微调整)
%   y2: 连续型输出2 (基于y1的衍生值，与y1强关联)
%   y3: 分类型输出 (根据y1和y2的数值特征划分，二分类：0/1)
%
% INPUT:
%   xx = [x1, x2, x3, x4]  % 4维输入向量
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

%% 1. 原始罗森布罗克函数核心计算逻辑
% 输入变量缩放
for ii = 1:4
    xxbar(:,ii) = 15*xx(:,ii) - 5;
end

% 罗森布罗克函数求和计算
sum_val = 0;  % 避免使用sum（MATLAB内置函数）
for ii = 1:3
    xibar = xxbar(:,ii);
    xnextbar = xxbar(:,ii+1);
    new = 100*(xnextbar-xibar.^2).^2 + (1-xibar).^2;
    sum_val = sum_val + new;
end

%% 2. 连续型输出1 (y1)：核心函数值（原函数基础上轻微调整）
y1 = (sum_val - 3.827*10^5) / (3.755*10^5);

%% 3. 连续型输出2 (y2)：与y1强关联的衍生值（加入微小随机噪声增强实用性）
% 关联逻辑：y2 = y1的非线性变换 + 微小噪声（保持关联性的同时增加真实感）
% rng(1);  % 随机数种子（可选，建模时可固定种子）
% noise = 0.01 * randn(size(y1));  % 0均值小方差噪声
% y2 = 2*y1.^2 + 0.5*y1;  % 与y1强关联的非线性变换
y2 = (sum_val.^1.5 - 1.27*10^8) / (2.55*10^8);
%% 4. 分类型输出3 (y3)：基于y1和y2的二分类结果（关联两个连续输出）
% 分类逻辑：当(y1 + y2)/2 < 0 时为0类，否则为1类（可根据需求调整为多分类）
y3 = zeros(size(y1));
% mean_yy = (y1 + y2) / 2;
mean_yy = 0.5*xxbar(:,1) + 0.3*xxbar(:,2).^2 - 0.4*xxbar(:,3).*xxbar(:,4) + 1.2*sin(pi*xxbar(:,1).*xxbar(:,3));
y3(mean_yy >= 0) = 1;

y=[y1,y2,y3];
end